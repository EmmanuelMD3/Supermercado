    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_jButton1ActionPerformed
    {//GEN-HEADEREND:event_jButton1ActionPerformed
        String nombre = nombreJT.getText().trim();
        String descripcion = descripcionJT.getText().trim();
        String precioCompraStr = precioCompraJT.getText().trim();
        String precioVentaStr = precioVentaJT.getText().trim();
        int stockMinimo = (Integer) stockMinS.getValue();
        int stockInicial = (Integer) stockInicialS.getValue();
        String categoriaSeleccionada = (String) categoriaCB.getSelectedItem();
        String proveedorSeleccionado = (String) provedorCB.getSelectedItem();
        boolean activo = activoCB.getSelectedItem().toString().equalsIgnoreCase("Activo");

        if (nombre.isEmpty() || precioCompraStr.isEmpty() || precioVentaStr.isEmpty()
                || categoriaSeleccionada == null || proveedorSeleccionado == null)
        {
            JOptionPane.showMessageDialog(this, "Todos los campos obligatorios deben estar llenos.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        double precioCompra;
        double precioVenta;
        try
        {
            precioCompra = Double.parseDouble(precioCompraStr);
            precioVenta = Double.parseDouble(precioVentaStr);
        } catch (NumberFormatException e)
        {
            JOptionPane.showMessageDialog(this, "Precios inválidos. Use solo números con punto decimal.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        CategoriaDAO categoriaDAO = new CategoriaDAO();
        ProvedorDAO provedorDAO = new ProvedorDAO();

        int categoriaId = categoriaDAO.obtenerIdPorNombre(categoriaSeleccionada);
        int proveedorId = provedorDAO.obtenerIdPorNombre(proveedorSeleccionado);

        if (categoriaId == -1 || proveedorId == -1)
        {
            JOptionPane.showMessageDialog(this, "Error al obtener ID de categoría o proveedor.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        Producto nuevoProducto = new Producto();
        nuevoProducto.setNombre(nombre);
        nuevoProducto.setDescripcion(descripcion);
        nuevoProducto.setPrecio_compra(precioCompra);
        nuevoProducto.setPrecio_venta(precioVenta);
        nuevoProducto.setStock_minimo(stockMinimo);
        nuevoProducto.setCategoria_id(categoriaId);
        nuevoProducto.setProveedor_id(proveedorId);
        nuevoProducto.setActivo(activo);

        ProductoDAO productoDAO = new ProductoDAO();
        int productoId = productoDAO.agregarProductoYObtenerId(nuevoProducto);

        if (productoId > 0)
        {
            InventarioDAO inventarioDAO = new InventarioDAO();
            Inventario inventario = new Inventario(productoId, stockInicial);
            boolean inventarioAgregado = inventarioDAO.insertarInventario(inventario);

            if (inventarioAgregado)
            {
                JOptionPane.showMessageDialog(this, "Producto e inventario registrados exitosamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                CtrlInterfaz.limpia(nombreJT, descripcionJT, precioCompraJT, precioVentaJT);
                stockMinS.setValue(1);
                stockInicialS.setValue(0);
                categoriaCB.setSelectedIndex(0);
                provedorCB.setSelectedIndex(0);
                activoCB.setSelectedItem("Activo");
                llenarTablaProductos();
            } else
            {
                JOptionPane.showMessageDialog(this, "Producto registrado pero falló el inventario.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            }
        } else
        {
            JOptionPane.showMessageDialog(this, "Ocurrió un error al registrar el producto.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_jButton2ActionPerformed
    {//GEN-HEADEREND:event_jButton2ActionPerformed
        int filaSeleccionada = tablaProductos.getSelectedRow();

        if (filaSeleccionada == -1)
        {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un producto para actualizar.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        DefaultTableModel modeloTabla = (DefaultTableModel) tablaProductos.getModel();

        String nombre = nombreJT.getText().trim();
        String descripcion = descripcionJT.getText().trim();
        String precioCompraStr = precioCompraJT.getText().trim();
        String precioVentaStr = precioVentaJT.getText().trim();
        int stockMinimo = (int) stockMinS.getValue();
        int nuevaCantidadInventario = (int) stockInicialS.getValue();
        String categoriaSeleccionada = (String) categoriaCB.getSelectedItem();
        String proveedorSeleccionado = (String) provedorCB.getSelectedItem();
        boolean activo = activoCB.getSelectedItem().toString().equalsIgnoreCase("Activo");

        if (nombre.isEmpty() || descripcion.isEmpty() || precioCompraStr.isEmpty() || precioVentaStr.isEmpty()
                || categoriaSeleccionada == null || proveedorSeleccionado == null)
        {
            JOptionPane.showMessageDialog(this, "Todos los campos deben estar llenos.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try
        {
            double precioCompra = Double.parseDouble(precioCompraStr);
            double precioVenta = Double.parseDouble(precioVentaStr);

            CategoriaDAO categoriaDAO = new CategoriaDAO();
            ProvedorDAO provedorDAO = new ProvedorDAO();

            int idCategoria = categoriaDAO.obtenerIdPorNombre(categoriaSeleccionada);
            int idProveedor = provedorDAO.obtenerIdPorNombre(proveedorSeleccionado);

            Object valorCelda = modeloTabla.getValueAt(filaSeleccionada, 0);
            int productoId = Integer.parseInt(valorCelda.toString());

            Producto producto = new Producto(nombre, descripcion, precioCompra, precioVenta, stockMinimo, idCategoria, idProveedor, activo);
            producto.setProducto_id(productoId);

            ProductoDAO productoDAO = new ProductoDAO();
            boolean exito = productoDAO.actualizarProducto(producto);

            InventarioDAO inventarioDAO = new InventarioDAO();
            boolean inventarioActualizado = inventarioDAO.actualizarCantidadInventario(productoId, nuevaCantidadInventario);

            if (exito)
            {
                if (!inventarioActualizado)
                {
                    JOptionPane.showMessageDialog(this, "Producto actualizado, pero ocurrió un error al actualizar el inventario.", "Advertencia", JOptionPane.WARNING_MESSAGE);
                } else
                {
                    JOptionPane.showMessageDialog(this, "Producto e inventario actualizados correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                }
                llenarTablaProductos();
            } else
            {
                JOptionPane.showMessageDialog(this, "Error al actualizar el producto.", "Error", JOptionPane.ERROR_MESSAGE);
            }

        } catch (NumberFormatException e)
        {
            JOptionPane.showMessageDialog(this, "Error al convertir precios o stock. Verifique los valores ingresados.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void tablaProductosMouseClicked(java.awt.event.MouseEvent evt)//GEN-FIRST:event_tablaProductosMouseClicked
    {//GEN-HEADEREND:event_tablaProductosMouseClicked
        int filaSeleccionada = tablaProductos.getSelectedRow();

        if (filaSeleccionada != -1)
        {
            DefaultTableModel modeloTabla = (DefaultTableModel) tablaProductos.getModel();

            String nombre = modeloTabla.getValueAt(filaSeleccionada, 1).toString();
            String descripcion = modeloTabla.getValueAt(filaSeleccionada, 2).toString();
            String precioCompra = modeloTabla.getValueAt(filaSeleccionada, 3).toString();
            String precioVenta = modeloTabla.getValueAt(filaSeleccionada, 4).toString();
            String stockMinimo = modeloTabla.getValueAt(filaSeleccionada, 5).toString();
            String categoria = modeloTabla.getValueAt(filaSeleccionada, 6).toString();
            String proveedor = modeloTabla.getValueAt(filaSeleccionada, 7).toString();
            String estado = modeloTabla.getValueAt(filaSeleccionada, 8).toString();

            int productoId = Integer.parseInt(modeloTabla.getValueAt(filaSeleccionada, 0).toString());

            nombreJT.setText(nombre);
            descripcionJT.setText(descripcion);
            precioCompraJT.setText(precioCompra);
            precioVentaJT.setText(precioVenta);
            stockMinS.setValue(Integer.parseInt(stockMinimo));
            categoriaCB.setSelectedItem(categoria);
            provedorCB.setSelectedItem(proveedor);

            InventarioDAO inventarioDAO = new InventarioDAO();
            int cantidadInventario = inventarioDAO.obtenerCantidadPorProductoId(productoId);
            stockInicialS.setValue(cantidadInventario);

            if (estado.equalsIgnoreCase("Activo"))
            {
                activoCB.setSelectedItem("Activo");
            } else
            {
                activoCB.setSelectedItem("Inactivo");
            }
        } else
        {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un producto.", "Advertencia", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_tablaProductosMouseClicked

