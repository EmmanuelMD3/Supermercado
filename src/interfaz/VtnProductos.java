    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_jButton4ActionPerformed
    {//GEN-HEADEREND:event_jButton4ActionPerformed
        int filaSeleccionada = tablaProductos.getSelectedRow();

        if (filaSeleccionada < 0 || filaSeleccionada >= tablaProductos.getRowCount())
        {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un producto válido.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        int confirmacion = JOptionPane.showConfirmDialog(
                this,
                "¿Está seguro de que desea eliminar el producto seleccionado?",
                "Confirmación",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE
        );

        if (confirmacion == JOptionPane.YES_OPTION)
        {
            DefaultTableModel modeloTabla = (DefaultTableModel) tablaProductos.getModel();
            Object valorCelda = modeloTabla.getValueAt(filaSeleccionada, 0);

            int productoID;
            try
            {
                productoID = Integer.parseInt(valorCelda.toString());
            } catch (NumberFormatException e)
            {
                JOptionPane.showMessageDialog(this, "Error al obtener el ID del producto.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            ProductoDAO productoDAO = new ProductoDAO();
            boolean exito = productoDAO.eliminarProducto(productoID);

            if (exito)
            {
                JOptionPane.showMessageDialog(this, "Producto eliminado correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                llenarTablaProductos();
                llenarTablaProductos();
            } else
            {
                JOptionPane.showMessageDialog(this, "Error al eliminar el producto.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButton4ActionPerformed

    private void llenarTablaProductos()
    {
        DefaultTableModel modelo = (DefaultTableModel) tablaProductos.getModel();
        modelo.setRowCount(0);

        ProductoDAO productoDAO = new ProductoDAO();
        List<Object[]> productos = productoDAO.listarProductosConNombres();

        for (Object[] fila : productos)
        {
            modelo.addRow(fila);
        }
    }

    public void filtrarProductos()
    {
        String textoBusqueda = buscar.getText().trim().toLowerCase();
        DefaultTableModel modeloTabla = (DefaultTableModel) tablaProductos.getModel();

        modeloTabla.setRowCount(0); 

        ProductoDAO productoDAO = new ProductoDAO();
        List<Object[]> productos = productoDAO.listarProductosConNombresYStock(); 

        for (Object[] fila : productos)
        {
            String nombreProducto = fila[1].toString().toLowerCase();
            if (nombreProducto.contains(textoBusqueda))
            {
                modeloTabla.addRow(fila);
            }
        }
    }

    public void llenarComboCategoria(JComboBox<String> comboCategoria)
    {
        CategoriaDAO categoriaDAO = new CategoriaDAO();

        List<Categoria> listaCategoria = categoriaDAO.obtenerTodosLasCategorias();

        DefaultComboBoxModel<String> modelo = new DefaultComboBoxModel<>();
        modelo.addElement("Seleccione una Categoria");

        for (Categoria categoria : listaCategoria)
        {
            modelo.addElement(categoria.getNombre());
        }
        comboCategoria.setModel(modelo);
    }

