    private void tablaProvedorMouseClicked(java.awt.event.MouseEvent evt)//GEN-FIRST:event_tablaProvedorMouseClicked
    {//GEN-HEADEREND:event_tablaProvedorMouseClicked
        int filaSeleccionada = tablaProvedor.getSelectedRow();

        if (filaSeleccionada != -1)
        {
            DefaultTableModel modeloTabla = (DefaultTableModel) tablaProvedor.getModel();

            String nombre = (String) modeloTabla.getValueAt(filaSeleccionada, 1);
            String contacto = (String) modeloTabla.getValueAt(filaSeleccionada, 2);
            String telefono = (String) modeloTabla.getValueAt(filaSeleccionada, 3);
            String email = (String) modeloTabla.getValueAt(filaSeleccionada, 4);
            String direccion = (String) modeloTabla.getValueAt(filaSeleccionada, 5);
            String estado = (String) modeloTabla.getValueAt(filaSeleccionada, 6);

            nombreJT.setText(nombre);
            contactoJT.setText(contacto);
            telefonoJT.setText(telefono);
            emailJT.setText(email);
            direccionJT.setText(direccion);

            if (estado.equalsIgnoreCase("Activo"))
            {
                activoCB.setSelectedItem("ACTIVO");
            } else
            {
                activoCB.setSelectedItem("INACTIVO");
            }
        } else
        {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un proveedor.", "Advertencia", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_tablaProvedorMouseClicked

