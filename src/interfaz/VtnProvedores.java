    private void jLabel7MouseClicked(java.awt.event.MouseEvent evt)//GEN-FIRST:event_jLabel7MouseClicked
    {//GEN-HEADEREND:event_jLabel7MouseClicked
        int filaSeleccionada = tablaProvedor.getSelectedRow();

        if (filaSeleccionada < 0 || filaSeleccionada >= tablaProvedor.getRowCount())
        {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un provedor valido.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        int confirmacion = JOptionPane.showConfirmDialog(
                this,
                "¿Está seguro de que desea eliminar el provedor seleccionado?",
                "Confirmación",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE
        );

        if (confirmacion == JOptionPane.YES_OPTION)
        {
            DefaultTableModel modeloTabla = (DefaultTableModel) tablaProvedor.getModel();
            Object valorCelda = tablaProvedor.getValueAt(filaSeleccionada, 0);

            long provedorID;
            try
            {
                provedorID = Long.parseLong(valorCelda.toString());
            } catch (NumberFormatException e)
            {
                JOptionPane.showMessageDialog(this, "Error al obtener el código de la categoría.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            ProvedorDAO provedorDAO = new ProvedorDAO();
            provedorDAO.eliminarProvedor(provedorID);

            llenarTablaProveedores();
            JOptionPane.showMessageDialog(this, "Categoría eliminada correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            CtrlInterfaz.limpia(nombreJT, contactoJT, telefonoJT, emailJT, direccionJT);
            activoCB.setSelectedIndex(0);

        }
    }//GEN-LAST:event_jLabel7MouseClicked

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_jButton3ActionPerformed
    {//GEN-HEADEREND:event_jButton3ActionPerformed
        int filaSeleccionada = tablaProvedor.getSelectedRow();

        if (filaSeleccionada == -1)
        {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un proveedor para actualizar.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        DefaultTableModel modeloTabla = (DefaultTableModel) tablaProvedor.getModel();

        String nuevoNombre = nombreJT.getText();
        String nuevoContacto = contactoJT.getText();
        String nuevoTelefono = telefonoJT.getText();
        String nuevoEmail = emailJT.getText();
        String nuevaDireccion = direccionJT.getText();
        String estadoSeleccionado = activoCB.getSelectedItem().toString();

        boolean activo = estadoSeleccionado.equalsIgnoreCase("Activo");

        Object valorCelda = modeloTabla.getValueAt(filaSeleccionada, 0);
        int proveedorId;

        try
        {
            proveedorId = Integer.parseInt(valorCelda.toString());
        } catch (NumberFormatException e)
        {
            JOptionPane.showMessageDialog(this, "Error al obtener el ID del proveedor.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        Provedor proveedorActualizado = new Provedor();
        proveedorActualizado.setProvedor_id(proveedorId);
        proveedorActualizado.setNombre(nuevoNombre);
        proveedorActualizado.setContacto(nuevoContacto);
        proveedorActualizado.setTelefono(nuevoTelefono);
        proveedorActualizado.setEmail(nuevoEmail);
        proveedorActualizado.setDireccion(nuevaDireccion);
        proveedorActualizado.setActivo(activo);

        ProvedorDAO proveedorDAO = new ProvedorDAO();
        boolean exito = proveedorDAO.modificarProveedor(proveedorActualizado);

        if (exito)
        {
            JOptionPane.showMessageDialog(this, "Proveedor actualizado correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            llenarTablaProveedores();
        } else
        {
            JOptionPane.showMessageDialog(this, "Error al actualizar el proveedor.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void llenarTablaProveedores()
    {
        DefaultTableModel modelo = (DefaultTableModel) tablaProvedor.getModel();

        modelo.setRowCount(0);

        List<modelo.Provedor> proveedores = ProvedorDAO.listarProveedores();

        for (modelo.Provedor proveedor : proveedores)
        {
            modelo.addRow(new Object[]
            {
                proveedor.getProvedor_id(),
                proveedor.getNombre(),
                proveedor.getContacto(),
                proveedor.getTelefono(),
                proveedor.getEmail(),
                proveedor.getDireccion(),
                proveedor.isActivo() ? "Activo" : "Inactivo",
                proveedor.getFecha_registro()
            });
        }
    }

    public void filtrarProveedores()
    {
        String textoBusqueda = buscar.getText().trim().toLowerCase();
        DefaultTableModel modeloTabla = (DefaultTableModel) tablaProvedor.getModel();

        modeloTabla.setRowCount(0);

        ProvedorDAO proveedorDAO = new ProvedorDAO();
        List<Provedor> proveedores = proveedorDAO.obtenerTodosLosProveedores();

        for (Provedor proveedor : proveedores)
        {
            if (proveedor.getNombre().toLowerCase().contains(textoBusqueda))
            {
                Object[] fila =
                {
                    proveedor.getNombre(),
                    proveedor.getContacto(),
                    proveedor.getTelefono(),
                    proveedor.getEmail(),
                    proveedor.getDireccion(),
                    proveedor.isActivo() ? "Activo" : "Inactivo"
                };
                modeloTabla.addRow(fila);
            }
        }
    }
    
    

    

