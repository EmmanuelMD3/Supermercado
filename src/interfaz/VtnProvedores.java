    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_jButton1ActionPerformed
    {//GEN-HEADEREND:event_jButton1ActionPerformed
        String nom = nombreJT.getText().trim();
        String contactoProv = contactoJT.getText().trim();
        String tel = telefonoJT.getText().trim();
        String correo = emailJT.getText().trim();
        String dir = direccionJT.getText().trim();
        boolean activo = activoCB.getSelectedItem().toString().equalsIgnoreCase("Activo");

        if (nom.isEmpty() || contactoProv.isEmpty() || tel.isEmpty() || correo.isEmpty() || dir.isEmpty())
        {
            JOptionPane.showMessageDialog(this, "Todos los campos deben estar llenos.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (!tel.matches("\\d{10}"))
        {
            JOptionPane.showMessageDialog(this, "Número de teléfono inválido. Debe contener exactamente 10 dígitos.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (!correo.matches("^[\\w.-]+@[\\w.-]+\\.\\w+$"))
        {
            JOptionPane.showMessageDialog(this, "Correo electrónico inválido.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        Provedor nuevoProveedor = new Provedor(nom, contactoProv, tel, correo, dir, activo);
        boolean registroExitoso = ProvedorDAO.agregarProveedor(nuevoProveedor);

        if (registroExitoso)
        {
            JOptionPane.showMessageDialog(this, "Proveedor registrado exitosamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            CtrlInterfaz.limpia(nombreJT, contactoJT, telefonoJT, emailJT, direccionJT);
            llenarTablaProveedores();
        } else
        {
            JOptionPane.showMessageDialog(this, "Ocurrió un error al registrar el proveedor.", "Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_jButton1ActionPerformed

