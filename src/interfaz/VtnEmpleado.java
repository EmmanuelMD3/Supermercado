    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_jButton1ActionPerformed
    {//GEN-HEADEREND:event_jButton1ActionPerformed

        String nombre = nombreJT.getText().trim();
        String apellido = apellidoJT.getText().trim();
        String telefono = telefonoJT.getText().trim();
        String email = coreoJT.getText().trim();
        String direccion = direccionJT.getText().trim();
        String password = contraseñaTF.getText().trim();
        String sueldo = sueldoJT.getText();
        int rol = rolCB.getSelectedIndex();
        String usuario = usuarioJT.getText();
        boolean activo = activoCB.getSelectedItem().toString().equalsIgnoreCase("Activo");

        if (nombre.isEmpty() || apellido.isEmpty() || telefono.isEmpty() || email.isEmpty() || direccion.isEmpty() || password.isEmpty() || usuario.isEmpty() || sueldo.isEmpty())
        {
            JOptionPane.showMessageDialog(this, "Todos los campos deben estar llenos.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (!telefono.matches("\\d{10}"))
        {
            JOptionPane.showMessageDialog(this, "Número de teléfono inválido. Debe contener exactamente 10 dígitos.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (!email.matches("^[\\w.-]+@[\\w.-]+\\.\\w+$"))
        {
            JOptionPane.showMessageDialog(this, "Correo electrónico inválido.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (fecha.getDate() == null)
        {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione una fecha.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        java.sql.Date fechaSeleccionada = new java.sql.Date(fecha.getDate().getTime());

        double salario = Double.parseDouble(sueldo);
        Empleado nuevoEmpleado = new Empleado(nombre, apellido, telefono, email, direccion, fechaSeleccionada, salario, rol, usuario, password, activo);

        boolean registroExitoso = EmpleadoDAO.agregarEmpleado(nuevoEmpleado);

        if (registroExitoso)
        {
            JOptionPane.showMessageDialog(this, "Empleado registrado exitosamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            CtrlInterfaz.limpia(nombreJT, apellidoJT, telefonoJT, contraseñaTF, direccionJT, coreoJT, sueldoJT, usuarioJT);
            fecha.setDate(null);
            rolCB.setSelectedIndex(0);
            activoCB.setSelectedIndex(0);
            llenarTablaEmpleados();
        } else
        {
            JOptionPane.showMessageDialog(this, "Ocurrió un error al registrar el cliente.", "Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_jButton1ActionPerformed

