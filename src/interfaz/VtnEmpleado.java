    private void llenarTablaEmpleados()
    {
        DefaultTableModel modeloTabla = (DefaultTableModel) tablaEmpleado.getModel();
        modeloTabla.setRowCount(0);

        List<Empleado> listarEmpleados = EmpleadoDAO.obtenerEmpleados();

        for (Empleado c : listarEmpleados)
        {
            String rolTexto;
            switch (c.getRol_id())
            {
                case 0:
                    rolTexto = "Administrador";
                    break;
                case 1:
                    rolTexto = "Cajero";
                    break;
                case 2:
                    rolTexto = "Empleado";
                    break;
                default:
                    rolTexto = "Desconocido";
                    break;
            }

            Object[] fila =
            {
                c.getEmpleado_id(),
                c.getNombre(),
                c.getApellido(),
                c.getTelefono(),
                c.getEmail(),
                c.getDireccion(),
                c.getFecha_contratación(),
                c.getSalario(),
                rolTexto,
                c.getUsuario(),
                c.getPassword(),
                c.isActivo() ? "Activo" : "Inactivo"
            };
            modeloTabla.addRow(fila);
        }
    }

    public void filtrarEmpleados()
    {
        String textoBusqueda = buscar.getText().trim().toLowerCase();
        DefaultTableModel modeloTabla = (DefaultTableModel) tablaEmpleado.getModel();

        modeloTabla.setRowCount(0);

        EmpleadoDAO empleadoDAO = new EmpleadoDAO();
        List<Empleado> empleados = empleadoDAO.obtenerTodosLosEmpleados();

        for (Empleado empleado : empleados)
        {
            if (empleado.getNombre().toLowerCase().contains(textoBusqueda))
            {
                Object[] fila =
                {
                    empleado.getEmpleado_id(),
                    empleado.getNombre(),
                    empleado.getApellido(),
                    empleado.getTelefono(),
                    empleado.getEmail(),
                    empleado.getDireccion(),
                    empleado.getFecha_contratación(),
                    empleado.getSalario(),
                    obtenerNombreRol(empleado.getRol_id()), // Si quieres mostrar el nombre del rol
                    empleado.getUsuario(),
                    empleado.getPassword(),
                    empleado.isActivo() ? "Activo" : "Inactivo"
                };
                modeloTabla.addRow(fila);
            }
        }
    }

    public String obtenerNombreRol(int rolId)
    {
        switch (rolId)
        {
            case 1:
                return "Administrador";
            case 2:
                return "Cajero";
            case 3:
                return "Empleado";
            default:
                return "Desconocido";
        }
    }


