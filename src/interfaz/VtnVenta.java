    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_jButton4ActionPerformed
    {//GEN-HEADEREND:event_jButton4ActionPerformed
        String nombreCliente = (String) clienteCB.getSelectedItem();

        if (nombreCliente == null || nombreCliente.equals("Seleccione un Cliente"))
        {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un cliente.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        ClienteDAO clienteDAO = new ClienteDAO();
        int clienteID = clienteDAO.obtenerIdPorNombreCompleto(nombreCliente);

        if (clienteID == -1)
        {
            JOptionPane.showMessageDialog(this, "Cliente no válido o no encontrado.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        int metodoPago = pagoCB.getSelectedIndex();
        double total = Double.parseDouble(campoTotalVenta.getText());
        double descuento = Double.parseDouble(campoDescuento.getText());
        double iva = Double.parseDouble(campoIVA.getText());

        Venta nuevaVenta = new Venta(total, descuento, iva, clienteID, idEmpleado, metodoPago, 1);

        DefaultTableModel modelo = (DefaultTableModel) tablaCarrito.getModel();
        List<DetallesVenta> listaDetalles = new ArrayList<>();

        for (int i = 0; i < modelo.getRowCount(); i++)
        {
            int idProducto = (int) modelo.getValueAt(i, 0);
            int cantidad = (int) modelo.getValueAt(i, 2);
            double precioU = (double) modelo.getValueAt(i, 3);
            double subtotal = (double) modelo.getValueAt(i, 4);

            DetallesVenta detalle = new DetallesVenta(0, idProducto, cantidad, precioU, subtotal);
            listaDetalles.add(detalle);
        }

        VentaDAO dao = new VentaDAO();
        boolean exito = dao.registrarVentaConDetalles(nuevaVenta, listaDetalles);

        if (exito)
        {
            JOptionPane.showMessageDialog(this, "¡Venta registrada correctamente!");
            limpiaCampos();
        } else
        {
            JOptionPane.showMessageDialog(this, "Error al registrar la venta. No se guardó nada.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton4ActionPerformed

    public void llenarComboCategoria(JComboBox<String> comboCategoria)
    {
        CategoriaDAO categoriaDAO = new CategoriaDAO();

        List<Categoria> listaCategoria = categoriaDAO.obtenerTodosLasCategorias();

        DefaultComboBoxModel<String> modelo = new DefaultComboBoxModel<>();
        modelo.addElement("Seleccione una Categoria");

        for (Categoria categoria : listaCategoria)
        {
            modelo.addElement(categoria.getNombre());
        }
        comboCategoria.setModel(modelo);
    }

    public void llenarComboCliente(JComboBox<String> comboCliente)
    {
        ClienteDAO clienteDAO = new ClienteDAO();

        List<Cliente> listaClientes = clienteDAO.obtenerTodosLosClientes();

        DefaultComboBoxModel<String> modelo = new DefaultComboBoxModel<>();
        modelo.addElement("Seleccione un Cliente");

        for (Cliente cliente : listaClientes)
        {
            String nombreCompleto = cliente.getNombre() + " " + cliente.getApellido();
            modelo.addElement(nombreCompleto);
        }

        comboCliente.setModel(modelo);
    }

    public void llenarTablaProductosPorCategoria(String nombreCategoria)
    {
        DefaultTableModel modeloTabla = (DefaultTableModel) tablaProductos.getModel();
        modeloTabla.setRowCount(0);

        ProductoDAO productoDAO = new ProductoDAO();
        List<Inventario> lista = productoDAO.obtenerProductosPorCategoria(nombreCategoria);

        for (Inventario inv : lista)
        {
            Object[] fila =
            {
                inv.getProducto_id(),
                inv.getNombre(),
                inv.getPrecio_venta(),
                inv.getCantidad()
            };
            modeloTabla.addRow(fila);
        }
    }

    private void actualizarResumenVenta()
    {
        double subtotal = 0;

        DefaultTableModel modelo = (DefaultTableModel) tablaCarrito.getModel();
        int filas = modelo.getRowCount();

        for (int i = 0; i < filas; i++)
        {
            double totalFila = Double.parseDouble(modelo.getValueAt(i, 4).toString());
            subtotal += totalFila;
        }

        double descuento = 0;
        if (subtotal > 1500)
        {
            descuento = subtotal * 0.05;
        } else if (subtotal > 1000)
        {
            descuento = subtotal * 0.03;
        }

        double iva = subtotal * 0.16;
        double total = subtotal + iva - descuento;

        campoSubtotal.setText(String.format("%.2f", subtotal));
        campoDescuento.setText(String.format("%.2f", descuento));
        campoIVA.setText(String.format("%.2f", iva));
        campoTotalVenta.setText(String.format("%.2f", total));
    }

    private void limpiaCampos()
    {
        DefaultTableModel modelo = (DefaultTableModel) tablaCarrito.getModel();
        modelo.setRowCount(0);

        DefaultTableModel modelo1 = (DefaultTableModel) tablaProductos.getModel();
        modelo1.setRowCount(0);

        CtrlInterfaz.limpia(campoSubtotal, campoDescuento, campoIVA, campoTotalVenta);

        cantidadJS.setValue(1);

        tablaProductos.clearSelection();
        categoriaCB.setSelectedIndex(0);
    }


