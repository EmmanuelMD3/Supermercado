    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_jButton1ActionPerformed
    {//GEN-HEADEREND:event_jButton1ActionPerformed
        int fila = tablaProductos.getSelectedRow();
        if (fila == -1)
        {
            JOptionPane.showMessageDialog(this, "Seleccione un producto.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int id = (int) tablaProductos.getValueAt(fila, 0);
        String nombre = tablaProductos.getValueAt(fila, 1).toString();
        double precio = Double.parseDouble(tablaProductos.getValueAt(fila, 2).toString());
        int stock = Integer.parseInt(tablaProductos.getValueAt(fila, 3).toString());
        int cantidad = (int) cantidadJS.getValue();

        if (cantidad <= 0)
        {
            JOptionPane.showMessageDialog(this, "La cantidad debe ser mayor a 0.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (cantidad > stock)
        {
            JOptionPane.showMessageDialog(this, "La cantidad excede el stock disponible.", "Stock insuficiente", JOptionPane.WARNING_MESSAGE);
            return;
        }

        double total = cantidad * precio;

        DefaultTableModel modelo = (DefaultTableModel) tablaCarrito.getModel();
        modelo.addRow(new Object[]
        {
            id,
            nombre,
            cantidad,
            precio,
            total
        });

        int nuevoStock = stock - cantidad;
        tablaProductos.setValueAt(nuevoStock, fila, 3);

        actualizarResumenVenta();
        cantidadJS.setValue(1);

    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_jButton2ActionPerformed
    {//GEN-HEADEREND:event_jButton2ActionPerformed
        int fila = tablaCarrito.getSelectedRow();

        if (fila >= 0)
        {
            DefaultTableModel modelo = (DefaultTableModel) tablaCarrito.getModel();
            modelo.removeRow(fila);
            actualizarResumenVenta();
        } else
        {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un producto del carrito para eliminar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_jButton3ActionPerformed
    {//GEN-HEADEREND:event_jButton3ActionPerformed
        int fila = tablaCarrito.getSelectedRow();

        if (fila >= 0)
        {
            int nuevaCantidad = (int) cantidadJS.getValue();

            if (nuevaCantidad <= 0)
            {
                JOptionPane.showMessageDialog(this, "La cantidad debe ser mayor que cero.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            DefaultTableModel modelo = (DefaultTableModel) tablaCarrito.getModel();

            double precioUnitario = Double.parseDouble(modelo.getValueAt(fila, 4).toString());
            double nuevoTotal = precioUnitario * nuevaCantidad;

            modelo.setValueAt(nuevaCantidad, fila, 2);
            modelo.setValueAt(nuevoTotal, fila, 4);

            actualizarResumenVenta();
        } else
        {
            JOptionPane.showMessageDialog(this, "Seleccione un producto del carrito para modificar la cantidad.", "Advertencia", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jButton3ActionPerformed

